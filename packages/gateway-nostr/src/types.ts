/**
 * Options and seams for `NostrAdapter`.
 *
 * @public
 */

import type { NostrRelayClient, NostrSocketFactory } from "./relay-client.js";

/**
 * The part of {@link NostrRelayClient} the adapter uses; tests pass a scripted one.
 *
 * @public
 */
export type NostrRelayLike = Pick<NostrRelayClient, "open" | "subscribe" | "publish" | "close">;

/**
 * Construction options for `NostrAdapter`.
 *
 * @public
 */
export interface NostrAdapterOptions {
  /**
   * The bot's nostr secret key, as an `nsec1…` key or 64 hex characters. It signs every event the
   * adapter publishes and decrypts every direct message sent to the bot; it never leaves the
   * process.
   *
   * @platform-term nsec (NIP-19 bech32 secret key), or the raw 32-byte hex key
   * @issued-at generated by the operator, for example `nak key generate` or any Nostr client's
   *   "create account"; no server issues it
   */
  readonly secretKey: string;
  /** The relay URLs to read from and publish to, each `wss:` (or `ws:`). At least one. */
  readonly relays: readonly string[];
  /**
   * Unix seconds before which a direct message is not answered, compared with the message's own
   * `created_at` (for NIP-17, the rumor's, never the wrap's). Default: the time of construction,
   * so a restart does not answer what the relay replays. A host that must answer exactly once
   * across restarts passes a persisted cursor.
   */
  readonly ignoreBefore?: number;
  /** Test seam: opens a relay socket. Default Node's global `WebSocket`. */
  readonly socketFactory?: NostrSocketFactory;
  /** Test seam: the relay client. Default a `NostrRelayClient` over `relays`. */
  readonly client?: NostrRelayLike;
}
